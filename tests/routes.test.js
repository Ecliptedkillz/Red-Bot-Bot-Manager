const assert = require('node:assert/strict');
const {parseRoute} = require('../web/routes.js');
const vm = require('node:vm'), fs = require('node:fs'), path = require('node:path');
const context = {module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../web/app.js'),'utf8').split('const $ =')[0], context);
for(const route of ['/','/admin','/cogs','/logs','/bots/new','/bots/import','/cogs/new','/bots/58484bb5e23a/console','/bots/58484bb5e23a/cogs/config%3AScamShield/settings'])assert.equal(JSON.stringify(context.module.exports.parseRoute(route)),JSON.stringify(parseRoute(route)));
const id='58484bb5e23a';
assert.deepEqual(parseRoute('/'),{view:'overview',botId:null});
assert.equal(parseRoute('/cogs').view,'cogs');
assert.equal(parseRoute('/logs/').view,'logs');
assert.equal(parseRoute('/admin').view,'admin');
assert.equal(parseRoute('/bots/new').view,'create');
assert.equal(parseRoute('/bots/import').view,'import');
assert.equal(parseRoute('/cogs/new').view,'upload');
assert.deepEqual(parseRoute(`/bots/${id}`),{botId:id,view:'bot',module:null});
assert.equal(parseRoute(`/bots/${id}/console`).view,'logs');
assert.equal(parseRoute(`/bots/${id}/cogs`).view,'cogs');
assert.equal(parseRoute(`/bots/${id}/settings`).view,'settings');
assert.deepEqual(parseRoute(`/bots/${id}/cogs/config%3AScamShield/settings`),{botId:id,view:'cogsettings',module:'config:ScamShield'});
for(const path of ['/unknown','/bots/nope',`/bots/${id}/console/example/settings`,`/bots/${id}/cogs/%ZZ/settings`])assert.equal(parseRoute(path).view,'notfound');
console.log('Portal route checks passed.');
